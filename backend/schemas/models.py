
from pydantic import BaseModel, Field, model_validator
from typing import List


# Resource requirements of a village
class ResourceRequirements(BaseModel):
    food_packets: int = Field(ge=0)
    water_liters: int = Field(ge=0)
    medical_kits: int = Field(ge=0)


# Information received about each village
class VillageInput(BaseModel):
    village_id: str
    village_name: str
    population: int = Field(gt=0)
    affected_population: int = Field(ge=0)
    severity: int = Field(ge=1, le=5)
    medical_urgency: int = Field(ge=1, le=5)
    required_resources: ResourceRequirements

    @model_validator(mode="after")
    def validate_affected_population(self):
        if self.affected_population > self.population:
            raise ValueError(
                "Affected population cannot exceed total population"
            )
        return self


# Assessment result generated by our module
class AssessmentResult(BaseModel):
    village_id: str
    priority_score: float = Field(ge=0, le=100)
    priority_level: str
    reason: str


# Request containing multiple villages
class AssessmentRequest(BaseModel):
    villages: List[VillageInput]
